//! Read-only Linux telemetry adapter for the Svelte System Monitor.
//! All presentation is in SystemWidget.svelte, never native GTK controls.
use std::cell::{Cell, RefCell};
use std::rc::Rc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, mpsc};
use std::time::Duration;

use crate::process_monitor::{ProcessSampler, ProcessSnapshot};
use crate::system_metrics::{Snapshot, bytes_label, percent_used};

/// Root filesystem data is queried on the GTK thread, like the Top Bar.
pub fn disk() -> Option<(u64, u64)> {
    let file = gtk::gio::File::for_path("/");
    use gtk::gio::prelude::*;
    let info = file
        .query_filesystem_info(
            "filesystem::size,filesystem::free",
            None::<&gtk::gio::Cancellable>,
        )
        .ok()?;
    let total = info.attribute_uint64("filesystem::size") / 1024;
    let available = info.attribute_uint64("filesystem::free") / 1024;
    (total > 0 && available <= total).then_some((total, available))
}

struct ProcessFeed {
    running: Arc<AtomicBool>,
    receiver: mpsc::Receiver<Result<ProcessSnapshot, String>>,
}

impl Drop for ProcessFeed {
    fn drop(&mut self) {
        self.running.store(false, Ordering::Relaxed);
    }
}

/// The UI may only start/stop a bounded, read-only sampler. No PID actions,
/// shell execution, command lines or generic Core RPC endpoints are exposed.
pub struct Model {
    metrics: Rc<RefCell<Snapshot>>,
    core: Rc<Cell<bool>>,
    niri: Rc<Cell<bool>>,
    processes: RefCell<Option<ProcessFeed>>,
}

impl Model {
    pub fn new(metrics: Rc<RefCell<Snapshot>>, core: Rc<Cell<bool>>, niri: Rc<Cell<bool>>) -> Self {
        Self {
            metrics,
            core,
            niri,
            processes: RefCell::new(None),
        }
    }

    pub fn metrics_json(&self) -> serde_json::Value {
        serde_json::json!({
            "metrics": self.metrics.borrow().as_json(),
            "core": self.core.get(),
            "niri": self.niri.get(),
        })
    }

    pub fn set_processes_active(&self, active: bool) {
        let mut feed = self.processes.borrow_mut();
        if !active {
            *feed = None;
            return;
        }
        if feed.is_some() {
            return;
        }
        let (sender, receiver) = mpsc::sync_channel(1);
        let running = Arc::new(AtomicBool::new(true));
        let alive = running.clone();
        std::thread::spawn(move || {
            let mut sampler = ProcessSampler::default();
            while alive.load(Ordering::Relaxed) {
                let result = sampler.sample().map_err(|error| error.to_string());
                // A slow UI must not queue unlimited /proc snapshots.
                match sender.try_send(result) {
                    Ok(()) | Err(mpsc::TrySendError::Full(_)) => {}
                    Err(mpsc::TrySendError::Disconnected(_)) => break,
                }
                std::thread::sleep(Duration::from_secs(2));
            }
        });
        *feed = Some(ProcessFeed { running, receiver });
    }

    pub fn poll_processes(&self) -> Option<serde_json::Value> {
        let feed = self.processes.borrow();
        let latest = feed.as_ref()?.receiver.try_recv().ok()?;
        Some(match latest {
            Ok(snapshot) => {
                // The native reader bounds scans to 4096 PIDs; preserve the
                // searchable full snapshot. Svelte renders only 36 visible rows.
                let rows: Vec<_> = snapshot
                    .rows
                    .iter()
                    .map(|row| {
                        serde_json::json!({
                            "pid": row.pid,
                            "name": row.name,
                            "state": row.state.to_string(),
                            "cpu_percent": row.cpu_percent,
                            "rss_kib": row.rss_kib,
                        })
                    })
                    .collect();
                serde_json::json!({
                    "rows": rows,
                    "total": snapshot.total,
                    "truncated": snapshot.truncated,
                    "error": null,
                })
            }
            Err(error) => serde_json::json!({
                "rows": [],
                "total": 0,
                "truncated": false,
                "error": error.chars().take(120).collect::<String>(),
            }),
        })
    }

    /// Clipboard text is generated by trusted Rust data, not arbitrary JS.
    pub fn report(&self) -> String {
        let s = self.metrics.borrow();
        let pair = |total: Option<u64>, available: Option<u64>| {
            total
                .zip(available)
                .map_or("UNAVAILABLE".to_string(), |(total, avail)| {
                    format!(
                        "{} / {}",
                        bytes_label(total.saturating_sub(avail)),
                        bytes_label(total)
                    )
                })
        };
        let load = s.load.map_or("UNAVAILABLE".to_string(), |v| {
            format!("{:.2} / {:.2} / {:.2}", v[0], v[1], v[2])
        });
        let uptime = s
            .uptime_seconds
            .map_or("UNAVAILABLE".to_string(), |seconds| {
                let days = seconds / 86_400;
                let hours = (seconds % 86_400) / 3_600;
                let minutes = (seconds % 3_600) / 60;
                if days > 0 {
                    format!("{days}d {hours}h {minutes}m")
                } else {
                    format!("{hours}h {minutes}m")
                }
            });
        let power = s
            .battery_percent
            .map_or("NOT DETECTED".to_string(), |battery| {
                let suffix = match s.battery_charging {
                    Some(true) => " / AC OR CHARGING",
                    Some(false) => " / DISCHARGING",
                    None => "",
                };
                format!("{battery}%{suffix}")
            });
        let root = pair(s.root_total_kib, s.root_available_kib);
        let memory = pair(s.memory_total_kib, s.memory_available_kib);
        let swap = pair(s.swap_total_kib, s.swap_free_kib);
        let health = if !self.core.get() {
            "CORE OFFLINE"
        } else if !self.niri.get() {
            "NIRI DISCONNECTED"
        } else if s
            .root_total_kib
            .zip(s.root_available_kib)
            .and_then(|(total, avail)| percent_used(total, avail))
            .is_some_and(|p| p >= 90)
        {
            "LOW STORAGE"
        } else if s.memory_percent().is_some_and(|p| p >= 90) {
            "MEMORY PRESSURE"
        } else {
            "SYSTEM STATUS"
        };
        format!(
            "KIRA SYSTEM / {health}\nCore: {}\nNiri: {}\nCPU: {}\nMemory: {memory}\nSwap: {swap}\nStorage /: {root}\nLoad 1/5/15: {load}\nUptime: {uptime}\nBattery: {power}",
            if self.core.get() {
                "CONNECTED"
            } else {
                "OFFLINE"
            },
            if self.niri.get() {
                "CONNECTED"
            } else {
                "DISCONNECTED"
            },
            s.cpu_percent
                .map_or("MEASURING".into(), |v| format!("{v}%")),
        )
    }
}

pub fn dismiss(app: &gtk::Application) -> bool {
    crate::calendar::dismiss_system(app)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sampler_is_activated_only_by_processes_tab() {
        let model = Model::new(
            Rc::new(RefCell::new(Snapshot::default())),
            Rc::new(Cell::new(false)),
            Rc::new(Cell::new(false)),
        );
        assert!(model.processes.borrow().is_none());
        model.set_processes_active(true);
        assert!(model.processes.borrow().is_some());
        model.set_processes_active(false);
        assert!(model.processes.borrow().is_none());
        assert!(model.report().contains("CORE OFFLINE"));
    }
}
